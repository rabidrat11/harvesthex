// Every weapon in the game. Held weapons are aimed by the player; cultivars
// are grown on the farm (or bought from Mags mid-run) and fight on their own.
// Behaviours live in sim/weapons.ts; this file is only numbers and words.

import type { EvolutionDef, WeaponDef, WeaponParams } from './types';

export const DEFAULT_PARAMS: WeaponParams = {
  damage: 10,
  cooldown: 1,
  speed: 250,
  range: 220,
  knockback: 40,
  count: 1,
  pierce: 0,
  area: 0,
  spread: 0.14,
  bounce: 0,
  duration: 0,
  burst: 1,
  burstGap: 0.09,
  split: 0,
  chain: 0,
  critBonus: 0,
};

function p(over: Partial<WeaponParams>): WeaponParams {
  return { ...DEFAULT_PARAMS, ...over };
}

export const WEAPONS: Record<string, WeaponDef> = {};

function def(w: WeaponDef): WeaponDef {
  WEAPONS[w.id] = w;
  return w;
}

