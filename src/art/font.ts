export interface BakedFont {
  key: string;
  w: number;
  h: number;
  data: Uint8ClampedArray;
  lineHeight: number;
  chars: { code: number; x: number; y: number; w: number; h: number; advance: number }[];
}

/** Bake a glyph font to an RGBA strip: white glyph, black 4-neighbour outline. */
export function bakeFont(f: GlyphFont): BakedFont {
  const entries = Object.entries(f.glyphs);
  const cellH = f.height + 2;
  let width = 0;
  const layout = entries.map(([ch, rows]) => {
    const gw = rows[0].length + 2;
    const x = width;
    width += gw + 1;
    return { ch, rows, x, gw };
  });
  const w = width;
  const h = cellH;
  const data = new Uint8ClampedArray(w * h * 4);
  const on = new Uint8Array(w * h);
  for (const g of layout) {
    g.rows.forEach((row, y) => {
      [...row].forEach((c, x) => {
        if (c !== '#') return;
        const px = g.x + 1 + x;
        const py = 1 + y;
        on[py * w + px] = 1;
      });
    });
  }
  for (let y = 0; y < h; y++)
    for (let x = 0; x < w; x++) {
      const i = (y * w + x) * 4;
      if (on[y * w + x]) {
        data[i] = data[i + 1] = data[i + 2] = 255;
        data[i + 3] = 255;
        continue;
      }
      const n = (x > 0 && on[y * w + x - 1]) || (x < w - 1 && on[y * w + x + 1]) || (y > 0 && on[(y - 1) * w + x]) || (y < h - 1 && on[(y + 1) * w + x]);
      if (n) data[i + 3] = 255;
    }
  return {
    key: f.key,
    w,
    h,
    data,
    lineHeight: cellH,
    chars: layout.map((g) => ({ code: g.ch.charCodeAt(0), x: g.x, y: 0, w: g.gw, h: cellH, advance: g.gw - 1 + f.spacing })),
  };
}
