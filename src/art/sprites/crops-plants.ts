function seedStage(name: string, seed: string[], h: number, sx = 6, sy = 9, mound = MOUND): string[] {
  const f = compose(W, N, [[mound, 0, 10], [seed, sx, sy]]);
  return frame(name, W, h, h === N ? f : bottom(W, h, f));
}

function crop(name: string, tall: boolean, frames: string[][]): SpriteDef {
  const h = tall ? T : N;
  frames.forEach((f, i) => frame(`${name}[${i}]`, W, h, f));
  return sprite(name, L, frames, { outline: true, origin: [0.5, 1] });
}

