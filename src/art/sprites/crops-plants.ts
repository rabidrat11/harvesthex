// Growth stages for the 12 crop species. Each crop has 4 frames:
// 0 seed in a mound, 1 sprout, 2 growing, 3 mature (produce visible).
// Normal crops are drawn 14x14 (16x16 after outline), tall ones 14x22 (16x24).
// Interior '#' lines separate fruit from foliage, as in the pack's food icons.
import { sprite, type SpriteDef } from '../sprite';
import { L, art, compose, frame, bottom } from './crops-kit';

const W = 14;
const N = 14; // normal height
const T = 22; // tall height

// Freshly turned mound of soil, lit from the top-left.
const MOUND = art('mound', [
  '.....cwww.....',
  '...ccwwwwwB...',
  '..cwwwwwwBBB..',
  '..BBwBBBBBBL..',
]);
