// Writes docs/ASSETS.md: every original sprite (group, frames, size) and every
// Cute Fantasy icon the game references, with licence notes.
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { SPRITE_GROUPS } from '../src/art/registry';
import { bakeDef } from '../src/art/sprite';
import { CF } from '../src/art/icons';

const PURPOSE: Record<string, string> = {
  characters: 'Player classes, held weapons, NPCs, portraits',
  creatures: 'Enemies, elites, the Marrow King and the Thousand-Eyed Scarecrow',
  crops: 'Crop growth stages, produce and seed packets',
  world: 'Terrain tiles, decor props, farm buildings',
  combat: 'Projectiles, hazards, enemy bullets, pickups, effects',
  ui: '9-slice frames, HUD icons, trait/damage icons, cursors, logo',
};

let out = `# Asset catalogue\n\n_Generated by \`npx vite-node tools/asset-catalogue.ts\`._\n\n`;
out += `## Sources and licences\n\n`;
out += `| Source | Licence | Use |\n|---|---|---|\n`;
out += `| Cute Fantasy Icons (free) by Kenmi, \`public/assets/cf-icons-16.png\` (copied unmodified from \`~/Downloads/Cute_Fantasy_Icons_Free/16x16/Free_Icons_all_16x16.png\`) | Non-commercial use; modification allowed; **no redistribution or resale** (see \`public/assets/cf-icons-LICENCE.txt\`) | Item, material, armour, tool, food and potion icons |\n`;
out += `| Original sprites in \`src/art/sprites/\` | Made for this project | Everything else (below) |\n`;
out += `| Pixelify Sans, Jacquard 24 (via @fontsource) | SIL Open Font License 1.1 | Interface text |\n`;
out += `| Sound and music (\`src/audio/\`) | Synthesised in code for this project | All audio |\n\n`;
out += `Original art uses the Endesga 64 palette (the pack's own palette) with the pack's black 1px outline. The 32px and 64px versions of the pack are nearest-neighbour upscales of the 16px set, so only the 16px sheet is used and the game scales it with everything else.\n\n`;
out += `## Cute Fantasy icons in use\n\n| Icon | Name in code | Used as |\n|---|---|---|\n`;
const srcFiles: string[] = [];
const walk = (d: string) => {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(ts|tsx)$/.test(f)) srcFiles.push(p);
  }
};
walk('src');
const allSrc = srcFiles.map((f) => readFileSync(f, 'utf8')).join('\n');
const used = Object.entries(CF).filter(([name, n]) => allSrc.includes(`CF.${name}`) || allSrc.includes(`'cf_${n}'`) || allSrc.includes(`"cf_${n}"`));
const usage = (name: string, n: number) => {
  const hits = srcFiles.filter((f) => readFileSync(f, 'utf8').includes(`CF.${name}`) || readFileSync(f, 'utf8').includes(`cf_${n}'`)).map((f) => f.replace('src/', '').replace(/\.tsx?$/, ''));
  return [...new Set(hits)].filter((h) => !h.includes('art/icons')).join(', ');
};
for (const [name, n] of used) out += `| ${n} | \`${name}\` | ${usage(name, n) || 'decor'} |\n`;
out += `\nAlso used as abandoned-tool decor in the meadow: icons 82, 122, 132, 142, 152, 162.\n\n`;
out += `## Original sprites\n\n`;
let total = 0;
let frames = 0;
for (const [g, defs] of Object.entries(SPRITE_GROUPS)) {
  const real = defs.filter((d) => !d.name.startsWith('preview_'));
  out += `### ${g} (${real.length})\n\n${PURPOSE[g]}. Source: \`src/art/sprites/${g}*.ts\`.\n\n| Sprite | Frames | Size |\n|---|---|---|\n`;
  for (const d of real) {
    const b = bakeDef(d);
    total++;
    frames += b.length;
    out += `| \`${d.name}\` | ${b.length} | ${b[0].w}x${b[0].h} |\n`;
  }
  out += '\n';
}
out = out.replace('## Original sprites\n\n', `## Original sprites\n\n${total} sprites, ${frames} frames.\n\n`);
writeFileSync('docs/ASSETS.md', out);
console.log(`wrote docs/ASSETS.md: ${used.length} pack icons referenced, ${total} original sprites, ${frames} frames`);
